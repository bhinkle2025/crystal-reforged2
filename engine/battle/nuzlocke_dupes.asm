NuzlockeCheckDuplicateFamily::
	ld a, [wEnemyMonSpecies]
	and a
	jr nz, .has_species
	ld c, a
	ret

.has_species:
	ld d, a
	ld hl, .Families

.next_family:
	ld a, [hl]
	and a
	jr z, .check_species
	push hl

.find_member:
	ld a, [hli]
	and a
	jr z, .not_this_family
	cp d
	jr nz, .find_member

	; Found the encountered Pokemon's family
	pop hl

.check_family:
	ld a, [hli]
	and a
	jr z, .not_caught
	push hl
	dec a
	call CheckCaughtMon
	pop hl
	jr nz, .caught
	jr .check_family

.not_this_family:
	pop bc
	jr .next_family

.check_species:
	; Other Pokemon retain same-species Dupes Clause
	ld a, [wEnemyMonSpecies]
	dec a
	jp CheckCaughtMon

.caught:
	ld c, 1
	ret

.not_caught:
	ld c, 0
	ret

